// renderIcon returns a complete inline <svg> for the named icon, or an empty
// template.HTML when the name is unknown. It never errors or panics: a missing
// icon simply renders nothing rather than breaking the page.
//
// extraClass is appended after the base "icon" class so callers can add a size
// or modifier (e.g. "sm", "brand-icon"). It is trimmed and skipped when blank
// so the class attribute is never left with a stray trailing space.
func renderIcon(name string, extraClass string) template.HTML {
	paths, ok := iconPaths[name]
	if !ok {
		return ""
	}
	class := "icon"
	if extra := strings.TrimSpace(extraClass); extra != "" {
		class = "icon " + extra
	}
	return template.HTML(`<svg class="` + class +
		`" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" ` +
		`stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">` +
		paths + `</svg>`)
}
